@dataclass(frozen=True, slots=True)
class BuiltPrompt:
    system_instructions: str
    user_content: str


class PromptBuilder:
    def build(
        self,
        *,
        question: str,
        context: ConversationContext,
    ) -> BuiltPrompt:
        payload = {
            "retrieved_document_chunks": [
                self._serialize_chunk(chunk) for chunk in context.retrieved_chunks
            ],
            "recent_completed_conversation": [
                {
                    "user": turn.user,
                    "assistant": turn.assistant,
                }
                for turn in context.recent_completed_turns
            ],
            "current_user_question": question,
        }

        return BuiltPrompt(
            system_instructions=SYSTEM_INSTRUCTIONS,
            user_content=json.dumps(
                payload,
                ensure_ascii=False,
                indent=2,
            ),
        )

    @staticmethod
    def _serialize_chunk(
        chunk: RetrievalResult,
    ) -> dict[str, Any]:
        provenance: dict[str, Any] = {
            "point_id": chunk.point_id,
            "document_id": chunk.document_id,
            "processing_run_id": (chunk.processing_run_id),
            "processing_profile": (chunk.processing_profile.value),
            "chunk_index": chunk.chunk_index,
            "source": chunk.source,
        }

        if chunk.page is not None:
            provenance["page"] = chunk.page

        if chunk.section is not None:
            provenance["section"] = chunk.section

        return {
            "provenance": provenance,
            "content": chunk.text,
        }
